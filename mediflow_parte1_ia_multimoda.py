import time

def consultar_gemini(
    prompt,
    archivo=None,
    modelos=None,
    intentos_por_modelo=2
):
    if modelos is None:
        modelos = [
            "gemini-3.8-flash",
            "gemini-3.1-flash-lite",
            "gemini-2.5-flash"
        ]

    # Gemini recibe el archivo y el prompt cuando hay un archivo adjunto
    contents = [archivo, prompt] if archivo else prompt

    for modelo in modelos:
        for intento in range(1, intentos_por_modelo + 1):
            try:
                print(
                    f"Intentando con {modelo} "
                    f"(intento {intento}/{intentos_por_modelo})"
                )

                respuesta = client.models.generate_content(
                    model=modelo,
                    contents=contents
                )

                if respuesta.text:
                    print(f"Respuesta obtenida con {modelo}.")
                    return respuesta.text

                print(f"{modelo} devolvió una respuesta vacía.")

            except Exception as e:
                print(
                    f"Falló {modelo}, intento "
                    f"{intento}/{intentos_por_modelo}: {e}"
                )

                if intento < intentos_por_modelo:
                    espera = 2 * intento
                    print(f"Reintentando en {espera} segundos...")
                    time.sleep(espera)

        print(f"El modelo {modelo} falló. Probando siguiente modelo...")

    raise RuntimeError(
        "No fue posible obtener una respuesta de ninguno de los modelos."
    )

