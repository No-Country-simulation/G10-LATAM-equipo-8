from langgraph.graph import StateGraph, START, END

# Nodos de salida del enrutamiento

def auditoria_humana(estado: EstadoMediFlow):
    return {
        "mensaje": "Documento enviado a auditoría humana."
    }


def emergencia(estado: EstadoMediFlow):
    return {
        "mensaje": "Documento enviado a la cola de emergencia. Se requiere alerta."
    }


def caso_estandar(estado: EstadoMediFlow):
    return {
        "mensaje": "Documento enviado al procesamiento estándar."
    }

# Nodo de persistencia

def persistencia(estado: EstadoMediFlow):
    return {
        "mensaje": estado["mensaje"] + " Documento listo para persistencia."
    }

# Nodo de notificación

def notificacion(estado: EstadoMediFlow):
    return {
        "mensaje": estado["mensaje"] + " Notificación generada."
    }

# Construcción del grafo de decisión

grafo = StateGraph(EstadoMediFlow)

grafo.add_node("detectar_urgencia", detectar_urgencia)
grafo.add_node("enrutar", enrutar)

grafo.add_node("auditoria_humana", auditoria_humana)
grafo.add_node("emergencia", emergencia)
grafo.add_node("caso_estandar", caso_estandar)

grafo.add_node("persistencia", persistencia)
grafo.add_node("notificacion", notificacion)

grafo.add_edge(START, "detectar_urgencia")
grafo.add_edge("detectar_urgencia", "enrutar")

grafo.add_conditional_edges(
    "enrutar",
    lambda estado: estado["ruta"],
    {
        "auditoria_humana": "auditoria_humana",
        "emergencia": "emergencia",
        "caso_estandar": "caso_estandar"
    }
)

grafo.add_edge("auditoria_humana", "persistencia")
grafo.add_edge("emergencia", "persistencia")
grafo.add_edge("caso_estandar", "persistencia")

grafo.add_edge("persistencia", "notificacion")
grafo.add_edge("notificacion", END)

# Compilar el grafo

app = grafo.compile()

print("Grafo compilado correctamente.")

