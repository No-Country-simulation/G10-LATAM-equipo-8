from typing import TypedDict

class EstadoMediFlow(TypedDict):
    extraccion_valida: bool
    confianza: float
    hay_inconsistencias: bool
    nivel_prioridad: str
    es_urgente: bool
    ruta: str
    mensaje: str

def detectar_urgencia(estado: EstadoMediFlow):
    es_urgente = estado["nivel_prioridad"] == "Urgente"

    return {
        "es_urgente": es_urgente
    }

# Umbral mínimo de confianza para procesamiento automático

UMBRAL_CONFIANZA = 0.80

print(f"Umbral de confianza: {UMBRAL_CONFIANZA:.0%}")

def enrutar(estado: EstadoMediFlow):

    if not estado["extraccion_valida"]:
        return {"ruta": "auditoria_humana"}

    if estado["es_urgente"]:
        return {"ruta": "emergencia"}

    if estado["hay_inconsistencias"]:
        return {"ruta": "auditoria_humana"}

    if estado["confianza"] < UMBRAL_CONFIANZA:
        return {"ruta": "auditoria_humana"}

    return {"ruta": "caso_estandar"}

