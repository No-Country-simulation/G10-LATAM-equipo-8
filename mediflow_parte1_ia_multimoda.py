# Función para cálculo de confianza
# basada en completitud y consistencia

def calcular_confianza(completitud, hay_inconsistencias):
    consistencia = 0.0 if hay_inconsistencias else 1.0

    confianza = (
        completitud * 0.60
        + consistencia * 0.40
    )

    return confianza

