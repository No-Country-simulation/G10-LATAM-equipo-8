# Cálculo del score de completitud

def score_completitud(extraccion):
    campos = [
        extraccion.tipo_documento,
        extraccion.canal_origen,
        extraccion.paciente.nombre,
        extraccion.paciente.edad,
        extraccion.medico_solicitante.nombre
            if extraccion.medico_solicitante else None,
        extraccion.medico_solicitante.matricula
            if extraccion.medico_solicitante else None,
        extraccion.estudio,
        extraccion.indicacion_clinica,
        extraccion.diagnostico_principal,
        extraccion.cie10_sugerido,
        extraccion.nivel_prioridad
    ]

    presentes = sum(
        1
        for campo in campos
        if campo is not None and str(campo).strip() != ""
    )

    total = len(campos)

    return presentes / total if total > 0 else 0.0

